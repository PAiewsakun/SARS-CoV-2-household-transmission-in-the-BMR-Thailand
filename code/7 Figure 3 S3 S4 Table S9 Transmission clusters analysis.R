# ###############################
# Sequence clustering analysis (only among our sequences)
# ###############################
# Compute pairwise sequence distance (in the units of time)
# -------------------------------
dist_matrix <- cophenetic(
  drop.tip(
    tree, 
    setdiff(tree$tip.label, seq_metadata %>% filter(source == "This study") %>% pull(seq_id))
  )
)

# Cluster sequences based on a (time) distance cutoff
# -------------------------------
# Clustering 
dist_cutoff <- (30/365)*2 # Differ by 30 days or fewer from the MRCA on average

clusters <- graph_from_adjacency_matrix(
  adjmatrix = (dist_matrix <= dist_cutoff),
  mode = "undirected",
  diag = FALSE) %>% 
  components

cluster_assignments <- clusters$membership

# For each cluster, check in the full tree if there are any sequences that are from outside of our cohort ...
# ... And the answer is "NO" :)
# -------------------------------
for(cluster_i in unique(cluster_assignments)) {
  cluster_i_tips <- names(cluster_assignments)[cluster_assignments == cluster_i]
  
  if(length(cluster_i_tips) > 1){
    sub_tree <- tree_subset(
      tree = tree,
      node = MRCA(tree, names(cluster_assignments)[cluster_assignments == cluster_i]),
      levels_back = 0
    )
    cluster_i_tips <- sub_tree$tip.label
  }
  
  seq_sources <- seq_metadata %>%
    filter(seq_id %in% cluster_i_tips) %>%
    pull(source)
  
  if (any(seq_sources != "This study")){
    print(sprintf("cluster %s contains GISAID public sequences!!!!!!!!!!!!!!!", cluster_i))
    print(cluster_i_tips)
  } else {
    print(sprintf("cluster %s contains sequences from our cohort only", cluster_i))
    print(cluster_i_tips)
  }
}

# Soft prune the time-calibrated phylogeny, ...
# to retain sequences from our cohort and their closest contextualising sequences only.
# Also, make soft_pruned_seq_metadata
# -------------------------------
# For each cluster, expand it to include its sister clade(s) by "levels_back" (1)
# The union set will be the set of tips to be retained in the pruned tree
levels_back = 1
tips_to_keep <- NULL
for(cluster_i in unique(cluster_assignments)) {
  expanded_cluster_i_tips <- tree_subset(
    tree = tree,
    node = MRCA(tree, names(cluster_assignments)[cluster_assignments == cluster_i]),
    levels_back = levels_back
  )$tip.label
  
  tips_to_keep <- c(tips_to_keep, expanded_cluster_i_tips)
}
tips_to_keep <- unique(tips_to_keep)

# Prune the tree to include only these tips
soft_pruned_tree <- drop.tip(tree, setdiff(tree$tip.label, tips_to_keep))

# Create soft_pruned_seq_metadata for the soft_pruned_tree
soft_pruned_seq_metadata <- seq_metadata %>% filter(seq_id %in% soft_pruned_tree$tip.label)

# Make cluster_metadata_soft_pruned_tree df for plotting Figure S3
# ----------------------------
# Plot the soft pruned tree to get data
soft_pruned_tree_plot <- ggtree(
  tr = soft_pruned_tree,
  mrsd = soft_pruned_seq_metadata %>% 
    pull(collection_date) %>% as.Date() %>% 
    sort(decreasing = TRUE) %>% head(1),
  ladderize = FALSE,
) %<+% soft_pruned_seq_metadata

soft_pruned_tree_data <- soft_pruned_tree_plot$data

cluster_metadata_soft_pruned_tree <- NULL
for(cluster_i in unique(cluster_assignments)) {
  # Tips that belong to this cluster
  cluster_i_tips <- names(cluster_assignments)[cluster_assignments == cluster_i]
  # Virus lineage
  cluster_i_major_lineage <- soft_pruned_tree_data %>% filter(label %in% cluster_i_tips) %>% pull(major_lineage) %>% unique()
  # Cluster size
  cluster_i_size <- length(cluster_i_tips)
  # MRCA node for these tips in the pruned tree
  cluster_i_MRCA_node <- MRCA(soft_pruned_tree, cluster_i_tips)
  # x coordinate of MRCA node
  cluster_i_MRCA_x <- soft_pruned_tree_data %>% filter(node == cluster_i_MRCA_node) %>% pull(x)
  # y coordinate of MRCA node
  cluster_i_MRCA_y <- soft_pruned_tree_data %>% filter(node == cluster_i_MRCA_node) %>% pull(y)
  
  # Just in case there are sequences from outside of our cohort in cluster_i,
  # Extract the clade from the MRCA node and update tip labels in that clade
  cluster_i_tips = if(length(cluster_i_tips) > 1){
    extract.clade(soft_pruned_tree, cluster_i_MRCA_node)$tip.label
  } else {
    cluster_i_tips
  }
  
  # For tips in this clade, get their max x coordinate from the tree data (Most Recent Sample date)
  cluster_i_MRS_x <- soft_pruned_tree_data %>% filter(isTip, label %in% cluster_i_tips) %>% pull(x) %>% max(na.rm = TRUE)
  # Compute cluster timescale as the difference between the MRS x coordinate and the MRCA x coordinate
  cluster_i_timescale <- cluster_i_MRS_x - cluster_i_MRCA_x
  
  # Determine HH
  cluster_i_HH <- soft_pruned_tree_data %>% filter(label %in% cluster_i_tips) %>% pull(family_id)
  # Determine first_HH_case_age_cat
  cluster_i_first_HH_case_age_cat <- first_HH_case_age_cat_dat %>% filter(family_id %in% cluster_i_HH) %>% pull(first_HH_case_age_cat) 
  # Determine if samples in cluster_i are from HH_with_complete_seq_dat
  cluster_i_HH_with_complete_seq_dat <- soft_pruned_tree_data %>% filter(label %in% cluster_i_tips) %>% pull(HH_with_complete_seq_dat)
  
  # Keep the results in the list cluster_metadata_soft_pruned_tree
  cluster_metadata_soft_pruned_tree[[as.character(cluster_i)]] <- list(
    tips = cluster_i_tips,
    HH = cluster_i_HH,
    first_HH_case_age_cat = cluster_i_first_HH_case_age_cat,
    HH_with_complete_seq_dat = cluster_i_HH_with_complete_seq_dat,
    major_lineage = cluster_i_major_lineage,
    size = cluster_i_size,
    MRCA_node = cluster_i_MRCA_node,
    MRCA_x = cluster_i_MRCA_x,
    MRCA_y = cluster_i_MRCA_y,
    MRS_x = cluster_i_MRS_x,
    timescale = cluster_i_timescale
  )
}

