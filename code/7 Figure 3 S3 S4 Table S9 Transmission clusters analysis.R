  tr = hard_pruned_tree,
  mrsd = hard_pruned_seq_metadata %>% 
    pull(collection_date) %>% as.Date() %>% 
    sort(decreasing = T) %>% head(1),
  ladderize = F,
) %<+% hard_pruned_seq_metadata

hard_pruned_tree_data <- hard_pruned_tree_plot$data

cluster_metadata_hard_pruned_tree <- NULL
for(cluster_i in unique(cluster_assignments)) {
  # Tips that belong to this cluster
  cluster_i_tips <- names(cluster_assignments)[cluster_assignments == cluster_i]
  # Virus lineage
  cluster_i_major_lineage <- hard_pruned_tree_data %>% filter(label %in% cluster_i_tips) %>% pull(major_lineage) %>% unique()
  # Cluster size
  cluster_i_size <- length(cluster_i_tips)
  # MRCA node for these tips in the hard_pruned tree
  cluster_i_MRCA_node <- MRCA(hard_pruned_tree, cluster_i_tips)
  # x coordinate of MRCA node
  cluster_i_MRCA_x <- hard_pruned_tree_data %>% filter(node == cluster_i_MRCA_node) %>% pull(x)
  # y coordinate of MRCA node
  cluster_i_MRCA_y <- hard_pruned_tree_data %>% filter(node == cluster_i_MRCA_node) %>% pull(y)
  
  # For these clade tips, get their max x coordinate from the tree data (Most Recent Sample date)
  cluster_i_MRS_x <- hard_pruned_tree_data %>% filter(isTip, label %in% cluster_i_tips) %>% pull(x) %>% max(na.rm = TRUE)
  # Compute timescale as the difference between the MRS x coordinate and the MRCA x coordinate
  cluster_i_timescale <- cluster_i_MRS_x - cluster_i_MRCA_x
  
  # Determine HH
  cluster_i_HH <- hard_pruned_tree_data %>% filter(label %in% cluster_i_tips) %>% pull(family_id)
  # Determine first_HH_case_age_cat
  cluster_i_first_HH_case_age_cat <- first_HH_case_age_cat_dat %>% filter(family_id %in% cluster_i_HH) %>% pull(first_HH_case_age_cat) 
  # Determine if samples in cluster_i are from HH_with_complete_seq_dat
  cluster_i_HH_with_complete_seq_dat <- hard_pruned_tree_data %>% filter(label %in% cluster_i_tips) %>% pull(HH_with_complete_seq_dat)
  
  # Keep the results in the list cluster_metadata_hard_pruned_tree
  cluster_metadata_hard_pruned_tree[[as.character(cluster_i)]] <- list(
    tips = cluster_i_tips,
    HH = cluster_i_HH,
    first_HH_case_age_cat = cluster_i_first_HH_case_age_cat,
    HH_with_complete_seq_dat = cluster_i_HH_with_complete_seq_dat,
    major_lineage = cluster_i_major_lineage,
    size = cluster_i_size,
    MRCA_node = cluster_i_MRCA_node,
    MRCA_x = cluster_i_MRCA_x,
    MRCA_y = cluster_i_MRCA_y,
    MRS_x = cluster_i_MRS_x,
    timescale = cluster_i_timescale
  )
}

